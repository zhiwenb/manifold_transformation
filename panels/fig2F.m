%% =====================================================================
%% Helper: significance star
%% =====================================================================

function add_sig_star( ...
    ax, ...
    x_pos, ...
    y_pos, ...
    p, ...
    font_size)

    if isnan(p)
        return;
    end

    if p < 0.001

        txt = '***';

    elseif p < 0.01

        txt = '**';

    elseif p < 0.05

        txt = '*';

    else

        % -------------------------------------------------
        % PNAS-style main figures do not necessarily need n.s. labels.
        % To show them, replace the empty string with 'n.s.'.
        % -------------------------------------------------

        txt = '';

    end

    if ~isempty(txt)

        text( ...
            ax, ...
            x_pos, ...
            y_pos, ...
            txt, ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','bottom', ...
            'FontName','Arial', ...
            'FontSize',font_size, ...
            'FontWeight','bold', ...
            'Interpreter','none');

    end

end

%% =====================================================================
%% Helper: changes
%% =====================================================================

function [ ...
    mean_change_T, ...
    mean_change_U, ...
    mean_baseline_T, ...
    mean_baseline_U ...
    ] = ...
    calculate_changes( ...
    day_data_T, ...
    T_cats, ...
    U_cats, ...
    day_idx, ...
    day_data_U)

    if nargin < 5
        day_data_U = day_data_T;
    end

    changes_T = [];
    changes_U = [];

    baseline_T = [];
    baseline_U = [];

    for i = 1:length(T_cats)

        cat_name = ...
            T_cats{i};

        if isfield( ...
                day_data_T, ...
                cat_name)

            val_post = ...
                day_data_T.(cat_name)(day_idx);

            val_base = ...
                day_data_T.(cat_name)(1);

            if ~isnan(val_post) && ...
                    ~isnan(val_base)

                change = ...
                    val_post - ...
                    val_base;

                changes_T = ...
                    [changes_T;change];

                baseline_T = ...
                    [baseline_T;val_base];

            end

        end

    end

    for i = 1:length(U_cats)

        cat_name = ...
            U_cats{i};

        if isfield( ...
                day_data_U, ...
                cat_name)

            val_post = ...
                day_data_U.(cat_name)(day_idx);

            val_base = ...
                day_data_U.(cat_name)(1);

            if ~isnan(val_post) && ...
                    ~isnan(val_base)

                change = ...
                    val_post - ...
                    val_base;

                changes_U = ...
                    [changes_U;change];

                baseline_U = ...
                    [baseline_U;val_base];

            end

        end

    end

    mean_change_T = ...
        mean(changes_T,'omitnan');

    mean_change_U = ...
        mean(changes_U,'omitnan');

    mean_baseline_T = ...
        mean(baseline_T,'omitnan');

    mean_baseline_U = ...
        mean(baseline_U,'omitnan');

end

%% =====================================================================
%% Helper: file parser
%% =====================================================================

function file_info = ...
    parse_files( ...
    mat_files, ...
    directory, ...
    sessions_in_group)

    file_info = struct( ...
        'name',{}, ...
        'path',{}, ...
        'session',{}, ...
        'datenum',{});

    for f_idx = 1:numel(mat_files)

        fileName = ...
            mat_files(f_idx).name;

        session_match = ...
            regexp( ...
            fileName, ...
            's(\d+)', ...
            'tokens');

        if isempty(session_match)
            continue;
        end

        session_name = ...
            sprintf( ...
            's%d', ...
            str2double( ...
            session_match{1}{1}));

        if ~ismember( ...
                session_name, ...
                sessions_in_group)

            continue;

        end

        date_match = ...
            regexp( ...
            fileName, ...
            '(\d{6})\.mat$', ...
            'tokens');

        if isempty(date_match)
            continue;
        end

        date_str = ...
            date_match{1}{1};

        year = ...
            2000 + ...
            str2double(date_str(5:6));

        month = ...
            str2double(date_str(1:2));

        day = ...
            str2double(date_str(3:4));

        file_info(end+1).name = ...
            fileName;

        file_info(end).path = ...
            fullfile( ...
            directory, ...
            fileName);

        file_info(end).session = ...
            session_name;

        file_info(end).datenum = ...
            datenum( ...
            year, ...
            month, ...
            day);

    end

end

%% =====================================================================
%% Helper: one-sample right-tailed t-test
%% =====================================================================

function p = ...
    one_sample_right_ttest(x)

    x = x(~isnan(x));

    if numel(x) < 2

        p = NaN;
        return;

    end

    [~,p] = ...
        ttest( ...
        x, ...
        0, ...
        'Tail','right');

end

%% =====================================================================
%% Helper: SEM
%% =====================================================================

function s = safe_sem(x)

    x = x(~isnan(x));

    if isempty(x)

        s = NaN;

    elseif numel(x) == 1

        s = 0;

    else

        s = ...
            std(x,0) / ...
            sqrt(numel(x));

    end

end