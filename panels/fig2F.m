%% =====================================================================
%  Analyze_Mechanism_PNAS_Subpanel.m
%
%  PNAS-style subpanel
%  Mechanism analysis:
%  Signal Enhancement vs Noise Reduction
%
%  Core definitions:
%    Distance contribution  > 0  = signal enhancement
%    -Variance contribution > 0  = noise reduction
%
%  Statistics:
%    One-sample t-test, right tail, against 0
%
%  Style:
%    1. Standalone PNAS subpanel.
%    2. Remove the large title.
%    3. Arial
%    4. Suitable for subsequent assembly in Affinity.
%    5. Export vector PDF and 600 dpi PNG/TIFF.
%% =====================================================================

clear; clc; close all;

%% =====================================================================
%% A. Basic configuration
%% =====================================================================

DATA_PARENT_DIRECTORY = ...
    figure_input('fig2');

target_sessions = {'s1','extra_var','s2','s3','s5'};

group_labels = {'L','L','L','G','G'};

%% =====================================================================
%% A.1 Category definitions
%% =====================================================================

session_T_categories = struct( ...
    's1',{{'T1','T2'}}, ...
    'extra_var',{{'T1','T2'}}, ...
    's2',{{'T1','T2'}}, ...
    's3',{{'T1','T2'}}, ...
    's5',{{'T1','T2','T3','T4'}});

session_U_categories = struct( ...
    's1',{{'U1','U2'}}, ...
    'extra_var',{{'U1','U2'}}, ...
    's2',{{'U1','U2'}}, ...
    's3',{{'U1','U2'}}, ...
    's5',{{'U1','U2','U3','U4'}});

%% =====================================================================
%% A.2 Neuron IDs
%% =====================================================================

session_config = struct();

session_config.s1.trained_ids = ...
    [7;8;9;12;13;14;17;18;19];

session_config.extra_var.trained_ids = ...
    [7;8;9;12;13;14;17;18;19];

session_config.s5.trained_ids = ...
    [7;8;9;12;13;14;17;18;19];

session_config.s2.trained_ids = ...
    [3;11;12;13;21];

session_config.s3.trained_ids = ...
    [10:18];

%% =====================================================================
%% A.3 Post-training window
%% =====================================================================

session_post_indices = struct();

session_post_indices.s1 = [3,4,5,6];
session_post_indices.s2 = [2,3];
session_post_indices.s3 = [2,3];
session_post_indices.s5 = [3,4,5,6];

%% =====================================================================
%% A.4 Data containers
%% =====================================================================

POOL_DIST = struct( ...
    'L',[], ...
    'G',[]);

POOL_VAR_INV = struct( ...
    'L',[], ...
    'G',[]);

%% =====================================================================
%% A.5 PNAS-style settings
%% =====================================================================

FONT_NAME = 'Arial';

FONT_TICK   = 8;
FONT_LABEL  = 9;
FONT_LEGEND = 8;
FONT_STAR   = 10;
FONT_PANEL  = 12;

% ---------------------------------------------------------
% Colors for the two mechanisms
%
% Distance = cool green
% -Variance = warm yellow/orange
% ---------------------------------------------------------

COLOR_DIST = [0.35,0.62,0.28];

COLOR_VAR  = [0.88,0.64,0.18];

% Optional lighter edges
EDGE_DIST = COLOR_DIST * 0.80;
EDGE_VAR  = COLOR_VAR  * 0.80;

%% =====================================================================
%% B. Data processing
%% =====================================================================

fprintf('Processing Data for Mechanism Analysis...\n');

for s_idx = 1:length(target_sessions)

    sess_name = ...
        target_sessions{s_idx};

    current_group = ...
        group_labels{s_idx};

    %% -----------------------------------------------------
    % Find files.
    %% -----------------------------------------------------

    sdi_path = fullfile( ...
        DATA_PARENT_DIRECTORY, ...
        'Results_SDI', ...
        current_group);

    mat_files = dir(fullfile( ...
        sdi_path, ...
        ['SDI_Results_FR_*' sess_name '*.mat']));

    if isempty(mat_files)

        mat_files = dir(fullfile( ...
            sdi_path, ...
            ['SDI_Results_FR_*' sess_name '.mat']));

    end

    file_info = parse_files( ...
        mat_files, ...
        sdi_path, ...
        {sess_name});

    if isempty(file_info)

        fprintf('No files for %s\n',sess_name);
        continue;

    end

    [~,sort_idx] = ...
        sort([file_info.datenum]);

    sorted_files = ...
        file_info(sort_idx);

    n_days = ...
        length(sorted_files);

    T_cats = ...
        session_T_categories.(sess_name);

    U_cats = ...
        session_U_categories.(sess_name);

    %% -----------------------------------------------------
    % Initialize.
    %% -----------------------------------------------------

    day_data_dist_T = struct();
    day_data_dist_U = struct();

    day_data_var_T = struct();
    day_data_var_U = struct();

    all_cats = [T_cats,U_cats];

    %% -----------------------------------------------------
    % Load data for each day.
    %% -----------------------------------------------------

    for day_idx = 1:n_days

        data = load( ...
            sorted_files(day_idx).path, ...
            'SDI_results');

        for cat_idx = 1:length(all_cats)

            cat_name = ...
                all_cats{cat_idx};

            if ~isfield(day_data_dist_T,cat_name)

                day_data_dist_T.(cat_name) = ...
                    nan(1,n_days);

            end

            if ~isfield(day_data_var_T,cat_name)

                day_data_var_T.(cat_name) = ...
                    nan(1,n_days);

            end

            if ~isfield(day_data_dist_U,cat_name)

                day_data_dist_U.(cat_name) = ...
                    nan(1,n_days);

            end

            if ~isfield(day_data_var_U,cat_name)

                day_data_var_U.(cat_name) = ...
                    nan(1,n_days);

            end

            if isfield( ...
                    data.SDI_results, ...
                    cat_name)

                res = ...
                    data.SDI_results.(cat_name);

                if any(strcmp(cat_name,T_cats))

                    day_data_dist_T.(cat_name)(day_idx) = ...
                        res.Mean_Trained_Distance;

                    day_data_var_T.(cat_name)(day_idx) = ...
                        res.Mean_Trained_Variance;

                else

                    day_data_dist_U.(cat_name)(day_idx) = ...
                        res.Mean_Control_Distance;

                    day_data_var_U.(cat_name)(day_idx) = ...
                        res.Mean_Control_Variance;

                end

            end

        end

    end

    %% -----------------------------------------------------
    % Compute DiD.
    %% -----------------------------------------------------

    if ~isfield( ...
            session_post_indices, ...
            sess_name)

        continue;

    end

    post_indices = ...
        session_post_indices.(sess_name);

    for day_idx = post_indices

        if day_idx > n_days
            continue;
        end

        [ ...
            d_T,d_U, ...
            base_dT,base_dU ...
            ] = ...
            calculate_changes( ...
            day_data_dist_T, ...
            T_cats, ...
            U_cats, ...
            day_idx, ...
            day_data_dist_U);

        [ ...
            v_T,v_U, ...
            base_vT,base_vU ...
            ] = ...
            calculate_changes( ...
            day_data_var_T, ...
            T_cats, ...
            U_cats, ...
            day_idx, ...
            day_data_var_U);

        if ...
                ~isnan(d_T) && ...
                ~isnan(d_U) && ...
                ~isnan(v_T) && ...
                ~isnan(v_U) && ...
                abs(base_dT) > eps && ...
                abs(base_dU) > eps && ...
                abs(base_vT) > eps && ...
                abs(base_vU) > eps

            %% Distance
            pct_dist_T = ...
                (d_T/base_dT)*100;

            pct_dist_U = ...
                (d_U/base_dU)*100;

            did_dist = ...
                pct_dist_T - ...
                pct_dist_U;

            %% Variance
            pct_var_T = ...
                (v_T/base_vT)*100;

            pct_var_U = ...
                (v_U/base_vU)*100;

            did_var_raw = ...
                pct_var_T - ...
                pct_var_U;

            % -------------------------------------------------
            % negative variance:
            % variance reduction -> positive contribution
            % -------------------------------------------------

            contribution_var = ...
                -did_var_raw;

            POOL_DIST.(current_group) = ...
                [ ...
                POOL_DIST.(current_group); ...
                did_dist ...
                ];

            POOL_VAR_INV.(current_group) = ...
                [ ...
                POOL_VAR_INV.(current_group); ...
                contribution_var ...
                ];

        end

    end

end

%% =====================================================================
%% C. Statistics
%% =====================================================================

fprintf('\n--- Statistics: one-sample t-test > 0 ---\n');

% =========================================================
% Remove NaNs.
% =========================================================

dist_L = ...
