fprintf( ...
    'M1 -Variance: N=%d, Mean=%.2f%%, p=%.4f\n', ...
    N_L_Var, ...
    Mean_L(2), ...
    p_L_Var);

fprintf( ...
    'M2 Distance: N=%d, Mean=%.2f%%, p=%.4f\n', ...
    N_G_Dist, ...
    Mean_G(1), ...
    p_G_Dist);

fprintf( ...
    'M2 -Variance: N=%d, Mean=%.2f%%, p=%.4f\n', ...
