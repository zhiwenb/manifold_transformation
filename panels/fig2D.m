%% =====================================================================
%% LOCAL FUNCTION 2
%% FIT PCA
%% =====================================================================

function [mu,sd_v,coeff,explained] = ...
    fit_day_pca( ...
        trained_data, ...
        control_data, ...
        N_PC)


XT = ...
    tensor_to_observations( ...
        trained_data);


XC = ...
    tensor_to_observations( ...
        control_data);


X = ...
    [XT;XC];


mu = ...
    mean( ...
        X, ...
        1, ...
        'omitnan');


sd_v = ...
    std( ...
        X, ...
        0, ...
        1, ...
        'omitnan');


sd_v(sd_v < eps) = ...
    1;


Xz = ...
    (X-mu) ./ ...
    sd_v;


Xz(~isfinite(Xz)) = ...
    0;


[coeff,~,~,~,explained] = ...
    pca(Xz);


if size(coeff,2) < N_PC

    error( ...
        'Only %d PCs available; requested %d.', ...
        size(coeff,2), ...
        N_PC);

end

end


