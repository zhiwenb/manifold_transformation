function X = ...
    tensor_to_observations(dat)


nNeuron = ...
    size(dat,1);


nCondition = ...
    size(dat,2);


nRep = ...
    size(dat,3);


tmp = ...
    permute( ...
        dat, ...
        [2 3 1]);


X = ...
    reshape( ...
        tmp, ...
        nCondition*nRep, ...
        nNeuron);

end


%% =====================================================================
%% LOCAL FUNCTION 5
%% GET MANIFOLD STATISTICS
%% =====================================================================

function [Cs,Vs] = ...
    get_manifold_stats( ...
        P, ...
        nCondition, ...
        nRep)


nDim = ...
    size(P,2);


expected_rows = ...
    nCondition*nRep;


if size(P,1) ~= expected_rows

    error( ...
        ['Projected observations = %d, expected %d ' ...
         '(%d conditions x %d repetitions).'], ...
        size(P,1), ...
        expected_rows, ...
        nCondition, ...
        nRep);

end


Cs = ...
    nan( ...
        nCondition, ...
        nDim);


Vs = ...
    cell( ...
        1, ...
        nCondition);


for i = 1:nCondition


    idx_start = ...
        (i-1)*nRep + 1;


    idx_end = ...
        i*nRep;


    Pi = ...
        P(idx_start:idx_end,:);


    Cs(i,:) = ...
        mean( ...
            Pi, ...
            1, ...
            'omitnan');


    if size(Pi,1) < 2


        Vs{i} = ...
            eye(nDim)*1e-6;


    else


        C = ...
            cov( ...
                Pi, ...
                'omitrows');


        if isempty(C) || ...
                any(~isfinite(C(:)))


            C = ...
                eye(nDim)*1e-6;


        end


        Vs{i} = ...
            regularize_cov(C);


    end

end

end


