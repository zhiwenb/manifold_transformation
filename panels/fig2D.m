%% =====================================================================
%% LOCAL FUNCTION 8
%% REGULARIZE COVARIANCE
%% =====================================================================

function C = ...
    regularize_cov(C)


C = ...
    (C+C')/2;


[V,D] = ...
    eig(C);


d = ...
    diag(D);


d(d < 1e-8) = ...
    1e-8;


C = ...
    V * ...
    diag(d) * ...
    V';


C = ...
    (C+C')/2;

end


%% =====================================================================
%% LOCAL FUNCTION 9
%% SORT EIGENVALUES
%% =====================================================================

function [V,D] = ...
    eig_sorted(C)


[V,D0] = ...
    eig(C);


[d,idx] = ...
    sort( ...
        diag(D0), ...
        'descend');


V = ...
    V(:,idx);


D = ...
    diag(d);

end