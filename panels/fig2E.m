    if isempty(mat_files)
        continue;
    end

    file_info = parse_files( ...
        mat_files, ...
        SDI_directory, ...
        current_sessions_in_group);

    if isempty(file_info)
        continue;
    end

    sessions = unique({file_info.session});

    for s_idx = 1:length(sessions)

        session_name = sessions{s_idx};

        session_mask = ...
            strcmp({file_info.session},session_name);

        session_files = ...
            file_info(session_mask);

        [~,sort_idx] = ...
            sort([session_files.datenum]);

        session_files = ...
            session_files(sort_idx);

        n_days = length(session_files);

        if n_days < 2
            continue;
        end

        T_cats = ...
            session_T_categories.(session_name);

        U_cats = ...
            session_U_categories.(session_name);

        trained_ids = ...
            session_config.(session_name).trained_ids;

        day_data_sdi = struct();

        all_cats = [T_cats,U_cats];

        for day_idx = 1:n_days

            data = load( ...
                session_files(day_idx).path, ...
                'SDI_results');

            for cat_idx = 1:length(all_cats)

                cat_name = all_cats{cat_idx};

                if ~isfield(day_data_sdi,cat_name)

                    day_data_sdi.(cat_name) = ...
                        nan(1,n_days);

                end

                if isfield(data.SDI_results,cat_name)

                    VALUE_matrix = ...
                        data.SDI_results.(cat_name).SDI_matrix;

                    values = ...
                        extract_pair_values( ...
                        VALUE_matrix, ...
                        trained_ids);

                    day_data_sdi.(cat_name)(day_idx) = ...
                        mean(values,'omitnan');

                end

            end

        end

        if isfield( ...
                session_post_indices, ...
                session_name)

            post_indices = ...
                session_post_indices.(session_name);

        else
            continue;
        end

        for day_idx = post_indices

            if day_idx > n_days
                continue;
            end

            [ ...
                mean_change_T, ...
                mean_change_U, ...
                base_T_sdi, ...
                base_U_sdi ...
                ] = ...
                calculate_changes( ...
                day_data_sdi, ...
                T_cats, ...
                U_cats, ...
                day_idx);

            if ~isnan(mean_change_T)

                pct_T = ...
                    (mean_change_T/base_T_sdi)*100;

                pct_U = ...
                    (mean_change_U/base_U_sdi)*100;

                GROUP_DID_POOL_SDI_RAW.(current_group) = ...
                    [ ...
                    GROUP_DID_POOL_SDI_RAW.(current_group); ...
                    pct_T-pct_U ...
                    ];

            end

        end

    end

end

