function plot_significance_single( ...
    ax, ...
    x_pos, ...
    y_pos, ...
    p_val, ...
    font_size)

    if isnan(p_val)

        sig_label = '';

    elseif p_val < 0.001

        sig_label = '***';

    elseif p_val < 0.01

        sig_label = '**';

    elseif p_val < 0.05

        sig_label = '*';

    else

        sig_label = '';

    end

    if ~isempty(sig_label)

        text( ...
            ax, ...
            x_pos, ...
            y_pos, ...
            sig_label, ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','bottom', ...
            'FontName','Arial', ...
            'FontSize',font_size, ...
            'FontWeight','bold', ...
            'Interpreter','none');

    end

end