    'SDI_M1', ...
    'SDI_M2', ...
    'SVM_M1', ...
    'SVM_M2'
    };

fprintf('\n--- Statistics (One-Sample T-Test vs 0, %% Improvement) ---\n');

for i = 1:length(Data_Pct)

    valid_data = ...
        Data_Pct{i}(~isnan(Data_Pct{i}));

    if numel(valid_data) >= 2

        [~,p,~,stats] = ...
            ttest(valid_data,0);

        Stats.(Labels{i}).p = p;
        Stats.(Labels{i}).stat_val = stats.tstat;

    else

        Stats.(Labels{i}).p = NaN;
        Stats.(Labels{i}).stat_val = NaN;

    end

    Mean_current = ...
        mean(valid_data,'omitnan');

    fprintf( ...
        '%s (N=%d): Mean=%.2f%%, T-Stat=%.3f, p=%.4f\n', ...
        Labels{i}, ...
        numel(valid_data), ...
        Mean_current, ...
        Stats.(Labels{i}).stat_val, ...
        Stats.(Labels{i}).p);

end

