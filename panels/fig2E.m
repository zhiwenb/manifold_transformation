function [ ...
    mean_change_T, ...
    mean_change_U, ...
    mean_baseline_T, ...
    mean_baseline_U ...
    ] = ...
    calculate_changes( ...
    day_data_T, ...
    T_cats, ...
    U_cats, ...
    day_idx, ...
    day_data_U)

    if nargin < 5
        day_data_U = day_data_T;
    end

    changes_T = [];
    changes_U = [];

    baseline_T = [];
    baseline_U = [];

    for i = 1:length(T_cats)

        cat_name = T_cats{i};

        if isfield(day_data_T,cat_name)

            change = ...
                day_data_T.(cat_name)(day_idx) - ...
                day_data_T.(cat_name)(1);

            changes_T = ...
                [changes_T;change];

            baseline_T = ...
                [baseline_T;day_data_T.(cat_name)(1)];

        end

    end

    for i = 1:length(U_cats)

        cat_name = U_cats{i};

        if isfield(day_data_U,cat_name)

            change = ...
                day_data_U.(cat_name)(day_idx) - ...
                day_data_U.(cat_name)(1);

            changes_U = ...
                [changes_U;change];

            baseline_U = ...
                [baseline_U;day_data_U.(cat_name)(1)];

        end

    end

    mean_change_T = ...
        mean(changes_T,'omitnan');

    mean_change_U = ...
        mean(changes_U,'omitnan');

    mean_baseline_T = ...
        mean(baseline_T,'omitnan');

    mean_baseline_U = ...
        mean(baseline_U,'omitnan');

end

%% =====================================================================

function file_info = ...
    parse_files( ...
    mat_files, ...
    directory, ...
    sessions_in_group)

    file_info = struct( ...
        'name',{}, ...
        'path',{}, ...
        'session',{}, ...
        'date',{}, ...
        'datenum',{});

    for f_idx = 1:numel(mat_files)

        fileName = ...
            mat_files(f_idx).name;

        filePath = ...
            fullfile(directory,fileName);

        session_match = ...
            regexp( ...
            fileName, ...
            's(\d+)', ...
            'tokens');

        if isempty(session_match)
            continue;
        end

        session_name = ...
            sprintf( ...
            's%d', ...
            str2double(session_match{1}{1}));

        if ~ismember( ...
                session_name, ...
                sessions_in_group)

            continue;

        end

        date_match = ...
            regexp( ...
            fileName, ...
            '(\d{6})\.mat$', ...
            'tokens');

        if isempty(date_match)
            continue;
        end

        date_str = ...
            date_match{1}{1};

        year = ...
            2000 + ...
            str2double(date_str(5:6));

        file_info(end+1).name = ...
            fileName;

        file_info(end).path = ...
            filePath;

        file_info(end).session = ...
            session_name;

        file_info(end).date = ...
            datetime( ...
            year, ...
            str2double(date_str(1:2)), ...
            str2double(date_str(3:4)));

        file_info(end).datenum = ...
            datenum(file_info(end).date);

    end

end

%% =====================================================================

function values = ...
    extract_pair_values( ...
    VALUE_matrix, ...
    ids)

    values = [];

    ids = ids(:);

    if isempty(ids)
        return;
    end

    pairs = ...
        nchoosek(ids,2);

    for k = 1:size(pairs,1)

        val = ...
            VALUE_matrix( ...
            pairs(k,1), ...
            pairs(k,2));

        if ~isnan(val)

            values = ...
                [values;val];

        end

    end

end

